/* Puente HACERLO / Laboratorio: validación, privacidad y visibilidad en IA. */
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const read=path=>fs.readFileSync(path,'utf8');
const core=read('src/core/app.js');
const bridge=read('src/modules/implementacion/laboratorio-resultados.js');
const lab=read('src/modules/implementacion/laboratorio.js');
const integrated=read('src/modules/inteligencia/integrada.js');
const ai=read('src/modules/inteligencia/ia.js');
const html=read('index.html');
const sandbox={console,Date,window:{},document:{getElementById:()=>null}};
sandbox.safe=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
vm.createContext(sandbox);
vm.runInContext("const HACERLO_LABORATORIO_URL='https://laboratorio.hacerlofc.com/';"+bridge,sandbox);
const data={orientations:['Colaborar','Crear','Lograr','Organizar'],current:[25,25,25,25],preferred:[30,20,30,20],
 dimensions:Array.from({length:6},(_,i)=>({name:'Dimensión '+(i+1),current:[25,25,25,25],preferred:[30,20,30,20]}))};
const raw={schema:'hacerlo.lab-result/1',simulator_id:'cultura-cvf',session_id:'TEST77',sample_size:6,
 captured_at:'2026-11-05T12:00:00.000Z',scope:'aggregate',data,participantEmail:'example@example.com',individualResults:[{name:'Persona'}]};
const norm=sandbox.labBridgeNormalizeReport(raw);
assert.equal(norm.simulator_id,'cultura-cvf');
assert.equal(norm.sample_size,6);
assert.equal(norm.data.dimensions.length,6);
assert.ok(!JSON.stringify(norm).includes('participantEmail'));
assert.ok(!JSON.stringify(norm).includes('individualResults'));
assert.throws(()=>sandbox.labBridgeNormalizeReport({...raw,sample_size:2}),/al menos tres/);
assert.throws(()=>sandbox.labBridgeNormalizeReport({...raw,scope:'individual'}),/perfiles colectivos/);
assert.throws(()=>sandbox.labBridgeNormalizeReport({...raw,session_id:'../secret'}),/código de sala/);
assert.throws(()=>sandbox.labBridgeNormalizeReport({...raw,data:{...data,current:[5,20,30,10]}}),/100 puntos/);
assert.throws(()=>sandbox.labBridgeNormalizeReport({...raw,data:{...data,dimensions:[]}}),/seis dimensiones/);
assert.throws(()=>sandbox.labBridgeNormalizeReport({...raw,simulator_id:'nexus'}),/Por ahora/);
const report={...norm,id:'00000000-0000-0000-0000-000000000001',provenance:'facilitator_export_unverified'};
const initiative={id:22,name:'Cultura de equipos',_cloudId:'00000000-0000-0000-0000-000000000002',labResults:[report]};
const htmlPanel=sandbox.labBridgeImportPanel(initiative);
assert.match(htmlPanel,/Importar consolidado/);
assert.match(htmlPanel,/Radar de Cultura/);
assert.match(htmlPanel,/Hoy 25 · Deseada 30/);
assert.doesNotMatch(htmlPanel,/example@example\.com/);
const aiContext=sandbox.labBridgeAIContext(initiative);
assert.equal(aiContext.records,1);
assert.equal(aiContext.sessions[0].verified,false);
assert.equal(aiContext.sessions[0].dimensions.length,6);
assert.match(sandbox.labBridgeIntegratedPanel(initiative),/sesión\(es\) vinculadas/);
assert.match(lab,/\$\{labBridgeImportPanel\(/);
assert.match(integrated,/labBridgeIntegratedPanel\(x\)/);
assert.match(ai,/laboratory:typeof labBridgeAIContext/);
assert.match(ai,/'labResults'/);
assert.match(core,/void labBridgeLoad\(current\(\),true\)/);
assert.ok(html.includes('src/modules/implementacion/laboratorio-resultados.js?v=1.0.0'));
assert.ok(html.includes('src/modules/inteligencia/ia.js?v=2.10.9'));
const scripts=[...html.matchAll(/<script src="([^"]+)" defer><\/script>/g)].map(m=>m[1]);
assert.ok(scripts.findIndex(s=>s.includes('laboratorio-resultados.js'))<scripts.findIndex(s=>s.includes('bootstrap.js')));
console.log('Puente Laboratorio OK: forma agregada, sin PII, lectura en integración e IA.');
