/* HACERLO · prueba del instrumento de Impacto y Esfuerzo. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {randomUUID}=require('node:crypto');
const read=p=>fs.readFileSync(p,'utf8');
const safe=s=>String(s??'').replace(/[&<>"']/g,k=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;','\'':'&#39;'}[k]));
const context={console,crypto:{randomUUID},safe,Math,Date};
vm.createContext(context);
vm.runInContext(read('src/modules/encuestas/motor.js'),context);
vm.runInContext(read('src/modules/encuestas/priorizacion.js'),context);
const Q=context.priorityQuestions();
assert.equal(Q.length,4);
assert.equal(Q.filter(q=>q.dimension==='Impacto').length,2);
assert.equal(Q.filter(q=>q.dimension==='Esfuerzo').length,2);
Q.forEach(q=>{
 assert.equal(q.type,'choice');
 assert.equal(q.priorityRandomized,true);
 assert.equal(q.required,true);
 assert.deepEqual(Array.from(q.optionScoring.options,o=>o.value),[1,3,5]);
 assert.equal(q.options.length,3);
 const shuffled=vm.runInContext('EE.shuffleChoices',context)(q);
 assert.deepEqual([...shuffled].sort(),[...q.options].sort());
 assert.notDeepEqual(shuffled,q.options,'No presentar siempre el orden 1, 3, 5');
 shuffled.forEach(answer=>assert.ok([1,3,5].includes(vm.runInContext('EE.optionScore',context)(q,answer))));
});
const s=context.priorityNewSurvey();
assert.equal(s.status,'draft');
assert.equal(s.instrumentKey,'priority-impact-effort');
assert.equal(context.priorityScoreReady(s),true);
assert.ok(context.priorityQuestionMarkup(s).includes('Se mantienen los resultados actuales.'));
assert.doesNotMatch(context.priorityQuestionMarkup(s),/optionScoring|>1<\/span>|>3<\/span>|>5<\/span>/);
const x={id:41,name:'Iniciativa de prueba',surveys:[s]};
const answerFor=choices=>Object.fromEntries(s.questions.map((q,index)=>[q.id,q.options[choices[index]]]));
context.priorityStoreResponse(x,s,answerFor([2,2,2,2]),'test');
context.priorityStoreResponse(x,s,answerFor([0,1,0,1]),'test');
assert.equal(s.status,'active');
const result=context.priorityResults(x);
assert.equal(result.n,2);
assert.equal(result.impact,3.5);
assert.equal(result.effort,3.5);
assert.equal(x.impact,3.5);
assert.equal(x.effort,3.5);
assert.equal(x.prioritySource,'priority-impact-effort');
s.responses.push({id:'partial',date:'2026-11-03T00:00:00.000Z',answers:{[s.questions[0].id]:s.questions[0].options[1]}});
assert.equal(context.priorityResults(x).n,2,'No promediar respuestas incompletas');
const s2=context.priorityNewSurvey();s2.version=2;
x.surveys.push(s2);
assert.equal(context.priorityResults(x).version,1,'La nueva versión vacía no borra evidencia anterior');
context.priorityStoreResponse(x,s2,answerFor([0,0,0,0]),'test');
assert.equal(context.priorityResults(x).version,2,'No promediar versiones diferentes');
assert.equal(x.impact,1);
assert.equal(x.effort,1);
const html=read('index.html');
assert.match(html,/src\/modules\/encuestas\/priorizacion\.js\?v=/);
assert.match(read('src/modules/encuestas/responder.js'),/EE\.shuffleChoices\(q\)/);
assert.match(read('src/core/iniciativas-home.js'),/priorityCreateForm/);
assert.match(read('src/core/iniciativas-home.js'),/priorityCardForm/);
assert.match(read('src/modules/medicion/paneles.js'),/priorityNavigateAssessment/);
console.log('Instrumento Impacto/Esfuerzo: plantilla, orden variable, puntuación oculta y consolidación correctos.');
